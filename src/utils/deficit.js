// حالة إقرار العجز من ملاحظات المحاسب. النص المحفوظ عند التأكيد أحد شكلين:
//   «[عجز X ر.س — تم إقرار العجز على الموظف ✓]»  أو  «[عجز X ر.س — لم يتم إقرار العجز]»
// تنبيه: العبارة «تم إقرار العجز» تقع داخل «لم يتم إقرار العجز» أيضاً، فالفحص بها وحدها يعدّ كل عجز مُقرّاً.
// يرجع 'yes' | 'no' | null (لا وسم عجز في الملاحظات)
export function deficitAck(notes) {
  const t = String(notes || '')
  if (t.includes('لم يتم إقرار العجز')) return 'no'
  if (t.includes('تم إقرار العجز على الموظف')) return 'yes'
  return null
}
