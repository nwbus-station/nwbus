const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const SORTED = [...Object.entries(PHRASES), ...Object.entries(WORDS)].sort((a, b) => b[0].length - a[0].length)
const AR = 'ء-ي'
// حدود الكلمة بالعربية: لا حرف عربي قبلها ولا بعدها (لتفادي استبدال جزء من كلمة)
const reFor = k => new RegExp(`(?<![${AR}])${esc(k)}(?![${AR}])`, 'g')
const COMPILED = SORTED.map(([k, v]) => [reFor(k), v])

// مشكَّل يدوياً = حركات كثيرة (التنوين وحده مثل «مروراً» لا يعني أن النص مشكَّل)
const manuallyVocalized = t => {
  const marks = (t.match(/[\u064B-\u0652\u0670]/g) || []).length
  const letters = (t.match(/[\u0621-\u064A]/g) || []).length
  return marks >= 3 && marks >= letters * 0.2
}

export function vocalize(text) {
  const t = String(text ?? '')
  if (!t || manuallyVocalized(t)) return t   // مشكَّل يدوياً: لا نلمسه
  let out = t
  for (const [re, v] of COMPILED) out = out.replace(re, v)
  return out
}
